/* STAAD.Pro input (.std) generator: a small model -> command file writer,
 * and builders for a box culvert (2D frame per metre run), a simple or
 * continuous beam, a portal frame and an aqueduct trough (U-frame).
 * STAAD.Pro is licensed software and must be installed separately; these
 * files are plain text and should be checked in STAAD before analysis. */
(function (root, factory) {
  var m = factory();
  if (typeof module === 'object' && module.exports) module.exports = m;
  else { root.DS = root.DS || {}; root.DS.staad = m; }
})(typeof self !== 'undefined' ? self : this, function () {
  'use strict';

  function n(x) { return String(Math.round(x * 10000) / 10000); }

  // [1,2,3,5,7,8,9] -> "1 TO 3 5 7 TO 9"
  function list(ids) {
    var a = ids.slice().sort(function (x, y) { return x - y; }), out = [], i = 0;
    while (i < a.length) {
      var j = i;
      while (j + 1 < a.length && a[j + 1] === a[j] + 1) j++;
      if (j - i >= 2) out.push(a[i] + ' TO ' + a[j]);
      else for (var k = i; k <= j; k++) out.push(String(a[k]));
      i = j + 1;
    }
    return out.join(' ');
  }

  /* model = {title, plane: true, comments: [..], joints: [[id,x,y]], members: [[id,j1,j2]],
   *   props: [{members, yd, zd}], material: {name, E (kN/m²), poisson, density (kN/m³), alpha},
   *   supports: [{joints, spec}], loads: [{id, type, title, selfweight, member: [{members, kind:'UNI'|'TRAP', dir, w | w1,w2}], joint: [{joints, fx, fy, mz}]}],
   *   combos: [{id, title, factors: [[loadId, f]]}] } */
  function write(model) {
    var L = [];
    L.push('STAAD ' + (model.plane === false ? 'SPACE' : 'PLANE') + ' ' + model.title.toUpperCase().replace(/[^A-Z0-9 .\-\/()]/g, ' ').slice(0, 70));
    L.push('* Generated by Design & Drawing Studio (preliminary design aid).');
    L.push('* STAAD.Pro is licensed software and must be installed separately.');
    (model.comments || []).forEach(function (c) { L.push('* ' + c); });
    L.push('START JOB INFORMATION');
    L.push('ENGINEER DATE ' + (model.date || new Date().toISOString().slice(0, 10)));
    L.push('END JOB INFORMATION');
    L.push('INPUT WIDTH 79');
    L.push('UNIT METER KN');
    L.push('JOINT COORDINATES');
    model.joints.forEach(function (j) { L.push(j[0] + ' ' + n(j[1]) + ' ' + n(j[2]) + ' 0;'); });
    L.push('MEMBER INCIDENCES');
    model.members.forEach(function (m) { L.push(m[0] + ' ' + m[1] + ' ' + m[2] + ';'); });
    var mat = model.material || {};
    L.push('DEFINE MATERIAL START');
    L.push('ISOTROPIC ' + (mat.name || 'CONCRETE'));
    L.push('E ' + n(mat.E || 2.5e7));
    L.push('POISSON ' + n(mat.poisson || 0.17));
    L.push('DENSITY ' + n(mat.density || 25));
    L.push('ALPHA ' + (mat.alpha || '1e-005'));
    L.push('DAMP 0.05');
    L.push('END DEFINE MATERIAL');
    L.push('MEMBER PROPERTY');
    model.props.forEach(function (p) { L.push(list(p.members) + ' PRIS YD ' + n(p.yd) + ' ZD ' + n(p.zd)); });
    L.push('CONSTANTS');
    L.push('MATERIAL ' + (mat.name || 'CONCRETE') + ' ALL');
    L.push('SUPPORTS');
    model.supports.forEach(function (s) { L.push(list(s.joints) + ' ' + s.spec); });
    model.loads.forEach(function (ld) {
      L.push('LOAD ' + ld.id + ' LOADTYPE ' + (ld.type || 'Dead') + ' TITLE ' + ld.title.toUpperCase());
      if (ld.selfweight) L.push('SELFWEIGHT Y ' + n(ld.selfweight));
      if (ld.member && ld.member.length) {
        L.push('MEMBER LOAD');
        ld.member.forEach(function (m) {
          if (m.kind === 'TRAP') L.push(list(m.members) + ' TRAP ' + m.dir + ' ' + n(m.w1) + ' ' + n(m.w2) +
            (m.d1 !== undefined ? ' ' + n(m.d1) + ' ' + n(m.d2) : ''));
          else L.push(list(m.members) + ' UNI ' + m.dir + ' ' + n(m.w));
        });
      }
      if (ld.joint && ld.joint.length) {
        L.push('JOINT LOAD');
        ld.joint.forEach(function (j) {
          var s = list(j.joints);
          if (j.fx) s += ' FX ' + n(j.fx);
          if (j.fy) s += ' FY ' + n(j.fy);
          if (j.mz) s += ' MZ ' + n(j.mz);
          L.push(s);
        });
      }
    });
    (model.combos || []).forEach(function (c) {
      L.push('LOAD COMB ' + c.id + ' ' + c.title.toUpperCase());
      L.push(c.factors.map(function (f) { return f[0] + ' ' + n(f[1]); }).join(' '));
    });
    L.push('PERFORM ANALYSIS PRINT STATICS CHECK');
    L.push('PRINT JOINT DISPLACEMENTS ALL');
    L.push('PRINT MEMBER FORCES ALL');
    L.push('PRINT SUPPORT REACTION ALL');
    L.push('FINISH');
    return L.join('\r\n') + '\r\n';
  }

  /* Box culvert, nCells cells, per metre run. p = {span, height (clear, m), nCells,
   * tTop, tBot, tWall (m), fill (m of earth above top slab), gammaSoil, K0, liveUDL (kN/m²),
   * subgrade (kN/m³), nSeg (bottom slab segments per cell), waterInside (bool)} */
  function boxCulvert(p) {
    var nc = p.nCells || 1, nseg = p.nSeg || 6;
    var Lc = p.span + p.tWall, Hc = p.height + (p.tTop + p.tBot) / 2;
    var joints = [], members = [], id = 1, mid = 1;
    var bottom = [], top = [];
    for (var c = 0; c < nc; c++) {
      for (var s = 0; s < nseg; s++) { bottom.push(id); joints.push([id++, c * Lc + s * Lc / nseg, 0]); }
    }
    bottom.push(id); joints.push([id++, nc * Lc, 0]);
    for (var w = 0; w <= nc; w++) { top.push(id); joints.push([id++, w * Lc, Hc]); }
    var botM = [], topM = [], wallM = [], outerL, outerR;
    for (var i = 0; i + 1 < bottom.length; i++) { botM.push(mid); members.push([mid++, bottom[i], bottom[i + 1]]); }
    for (w = 0; w <= nc; w++) {
      var jb = bottom[w * nseg], jt = top[w];
      wallM.push(mid);
      if (w === 0) outerL = mid;
      if (w === nc) outerR = mid;
      members.push([mid++, jb, jt]);           // walls drawn bottom -> top
    }
    for (w = 0; w < nc; w++) { topM.push(mid); members.push([mid++, top[w], top[w + 1]]); }
    var gs = p.gammaSoil || 18, K0 = p.K0 || 0.5, gw = 9.81;
    var zTop = p.fill + p.tTop / 2, zBot = zTop + Hc;
    var supports = [];
    var k = (p.subgrade || 20000);
    bottom.forEach(function (j, idx) {
      var trib = (idx === 0 || idx === bottom.length - 1) ? Lc / nseg / 2 : Lc / nseg;
      var kn = k * trib * 1.0;
      supports.push({ joints: [j], spec: (idx === 0 ? 'FIXED BUT MZ KFY ' : 'FIXED BUT FX MZ KFY ') + n(kn) });
    });
    var loads = [
      { id: 1, type: 'Dead', title: 'SELF WEIGHT', selfweight: -1 },
      { id: 2, type: 'Dead', title: 'EARTH FILL ON TOP SLAB', member: [{ members: topM, kind: 'UNI', dir: 'GY', w: -gs * p.fill }] },
      { id: 3, type: 'Soil', title: 'LATERAL EARTH PRESSURE', member: [
        { members: [outerL], kind: 'TRAP', dir: 'GX', w1: K0 * gs * zBot, w2: K0 * gs * zTop },
        { members: [outerR], kind: 'TRAP', dir: 'GX', w1: -K0 * gs * zBot, w2: -K0 * gs * zTop }] },
      { id: 4, type: 'Fluids', title: 'WATER INSIDE CELLS', member: [] },
      { id: 5, type: 'Live', title: 'LIVE LOAD AS UDL', member: [{ members: topM, kind: 'UNI', dir: 'GY', w: -(p.liveUDL || 0) },
        { members: [outerL], kind: 'UNI', dir: 'GX', w: K0 * (p.liveUDL || 0) },
        { members: [outerR], kind: 'UNI', dir: 'GX', w: -K0 * (p.liveUDL || 0) }] }
    ];
    // water inside each cell: outward pressure on cell walls, weight on bottom slab
    for (c = 0; c < nc; c++) {
      var wl = wallM[c], wr = wallM[c + 1];
      loads[3].member.push({ members: [wl], kind: 'TRAP', dir: 'GX', w1: -gw * Hc, w2: 0 });
      loads[3].member.push({ members: [wr], kind: 'TRAP', dir: 'GX', w1: gw * Hc, w2: 0 });
      loads[3].member.push({ members: botM.slice(c * nseg, (c + 1) * nseg), kind: 'UNI', dir: 'GY', w: -gw * p.height });
    }
    // interior walls get equal and opposite pressure from both cells; keep entries (they cancel in analysis)
    return {
      title: 'BOX CULVERT ' + nc + ' CELL PER METRE RUN',
      comments: [
        'Clear span ' + p.span + ' m x clear height ' + p.height + ' m, ' + nc + ' cell(s); centre-line frame ' + n(Lc) + ' x ' + n(Hc) + ' m.',
        'Slabs/walls: top ' + p.tTop + ' m, bottom ' + p.tBot + ' m, walls ' + p.tWall + ' m. Fill above top slab ' + p.fill + ' m.',
        'Earth pressure at rest K0 = ' + K0 + ', soil unit weight ' + gs + ' kN/m3; live load ' + (p.liveUDL || 0) + ' kN/m2 as UDL.',
        'Bottom slab on soil springs, modulus of subgrade reaction ' + k + ' kN/m3 (verify from soil data).',
        'Combination factors below are placeholders - apply IRC:6 partial factors (verify).'
      ],
      joints: joints, members: members,
      props: [{ members: topM, yd: p.tTop, zd: 1 }, { members: botM, yd: p.tBot, zd: 1 }, { members: wallM, yd: p.tWall, zd: 1 }],
      material: { name: 'CONCRETE', E: 5000 * Math.sqrt(p.fck || 30) * 1000, poisson: 0.17, density: 25 },
      supports: supports, loads: loads,
      combos: [
        { id: 101, title: 'SERVICE EMPTY + LL', factors: [[1, 1], [2, 1], [3, 1], [5, 1]] },
        { id: 102, title: 'SERVICE FULL NO LL', factors: [[1, 1], [2, 1], [3, 1], [4, 1]] },
        { id: 103, title: 'SERVICE FULL + LL', factors: [[1, 1], [2, 1], [3, 1], [4, 1], [5, 1]] },
        { id: 201, title: 'ULTIMATE EMPTY + LL', factors: [[1, 1.35], [2, 1.35], [3, 1.5], [5, 1.5]] },
        { id: 202, title: 'ULTIMATE FULL + LL', factors: [[1, 1.35], [2, 1.35], [3, 1.5], [4, 1.5], [5, 1.5]] }
      ]
    };
  }

  /* Continuous beam over supports. p = {spans: [m..], b, D, dl (kN/m, excl. self weight), ll (kN/m)} */
  function beam(p) {
    var x = 0, joints = [[1, 0, 0]], members = [];
    p.spans.forEach(function (s, i) { x += s; joints.push([i + 2, x, 0]); members.push([i + 1, i + 1, i + 2]); });
    var all = members.map(function (m) { return m[0]; });
    var sup = [{ joints: [1], spec: 'PINNED' }];
    if (joints.length > 1) sup.push({ joints: joints.slice(1).map(function (j) { return j[0]; }), spec: 'FIXED BUT FX MZ' });
    return {
      title: (p.spans.length > 1 ? 'CONTINUOUS BEAM ' + p.spans.length + ' SPANS' : 'SIMPLY SUPPORTED BEAM'),
      comments: ['Beam ' + p.b + ' x ' + p.D + ' m; spans ' + p.spans.join(', ') + ' m.', 'Dead load (excluding self weight) ' + p.dl + ' kN/m, live load ' + p.ll + ' kN/m.'],
      joints: joints, members: members,
      props: [{ members: all, yd: p.D, zd: p.b }],
      material: { name: 'CONCRETE', E: 5000 * Math.sqrt(p.fck || 25) * 1000, poisson: 0.17, density: 25 },
      supports: sup,
      loads: [
        { id: 1, type: 'Dead', title: 'DEAD LOAD', selfweight: -1, member: [{ members: all, kind: 'UNI', dir: 'GY', w: -p.dl }] },
        { id: 2, type: 'Live', title: 'LIVE LOAD', member: [{ members: all, kind: 'UNI', dir: 'GY', w: -p.ll }] }
      ],
      combos: [{ id: 101, title: 'SERVICE DL + LL', factors: [[1, 1], [2, 1]] }, { id: 201, title: 'IS 456 1.5 DL + 1.5 LL', factors: [[1, 1.5], [2, 1.5]] }]
    };
  }

  /* Portal frame with nBays bays. p = {span, height, nBays, colB, colD, beamB, beamD, dl, ll (kN/m on beams), lateral (kN at top left)} */
  function portal(p) {
    var nb = p.nBays || 1, joints = [], members = [], id = 1;
    var bases = [], tops = [];
    for (var i = 0; i <= nb; i++) { bases.push(id); joints.push([id++, i * p.span, 0]); }
    for (i = 0; i <= nb; i++) { tops.push(id); joints.push([id++, i * p.span, p.height]); }
    var cols = [], beams = [], m = 1;
    for (i = 0; i <= nb; i++) { cols.push(m); members.push([m++, bases[i], tops[i]]); }
    for (i = 0; i < nb; i++) { beams.push(m); members.push([m++, tops[i], tops[i + 1]]); }
    return {
      title: 'PORTAL FRAME ' + nb + ' BAY',
      comments: ['Bay width ' + p.span + ' m, height ' + p.height + ' m; columns ' + p.colB + ' x ' + p.colD + ' m, beams ' + p.beamB + ' x ' + p.beamD + ' m.', 'Fixed column bases.'],
      joints: joints, members: members,
      props: [{ members: cols, yd: p.colD, zd: p.colB }, { members: beams, yd: p.beamD, zd: p.beamB }],
      material: { name: 'CONCRETE', E: 5000 * Math.sqrt(p.fck || 25) * 1000, poisson: 0.17, density: 25 },
      supports: [{ joints: bases, spec: 'FIXED' }],
      loads: [
        { id: 1, type: 'Dead', title: 'DEAD LOAD', selfweight: -1, member: [{ members: beams, kind: 'UNI', dir: 'GY', w: -p.dl }] },
        { id: 2, type: 'Live', title: 'LIVE LOAD', member: [{ members: beams, kind: 'UNI', dir: 'GY', w: -p.ll }] },
        { id: 3, type: 'Wind', title: 'LATERAL LOAD', joint: [{ joints: [tops[0]], fx: p.lateral || 0 }] }
      ],
      combos: [
        { id: 101, title: 'SERVICE DL + LL', factors: [[1, 1], [2, 1]] },
        { id: 201, title: '1.5 DL + 1.5 LL', factors: [[1, 1.5], [2, 1.5]] },
        { id: 202, title: '1.2 DL + 1.2 LL + 1.2 LAT', factors: [[1, 1.2], [2, 1.2], [3, 1.2]] }
      ]
    };
  }

  /* Aqueduct trough, transverse U-frame per metre length.
   * p = {width (clear), depth (water depth), wallH (clear wall height), tWall, tSlab, nSeg, walkway (kN/m² LL on slab), fck} */
  function trough(p) {
    var nseg = p.nSeg || 6, Wc = p.width + p.tWall, Hc = p.wallH + p.tSlab / 2;
    var joints = [], members = [], id = 1, m = 1, bot = [];
    for (var s = 0; s <= nseg; s++) { bot.push(id); joints.push([id++, s * Wc / nseg, 0]); }
    var tl = id; joints.push([id++, 0, Hc]);
    var tr = id; joints.push([id++, Wc, Hc]);
    var slab = [];
    for (s = 0; s < nseg; s++) { slab.push(m); members.push([m++, bot[s], bot[s + 1]]); }
    var wl = m; members.push([m++, bot[0], tl]);
    var wr = m; members.push([m++, bot[nseg], tr]);
    var gw = 9.81, d = Math.min(p.depth, p.wallH);
    return {
      title: 'AQUEDUCT TROUGH TRANSVERSE U FRAME',
      comments: ['Clear width ' + p.width + ' m, water depth ' + p.depth + ' m, wall height ' + p.wallH + ' m.',
        'Walls ' + p.tWall + ' m, bottom slab ' + p.tSlab + ' m; per metre length of trough.',
        'Supported at the bottom corners (on longitudinal beams/piers): left pinned, right roller.',
        'Water pressure is applied as a triangle over the wetted part of each wall (TRAP with distances).'],
      joints: joints, members: members,
      props: [{ members: slab, yd: p.tSlab, zd: 1 }, { members: [wl, wr], yd: p.tWall, zd: 1 }],
      material: { name: 'CONCRETE', E: 5000 * Math.sqrt(p.fck || 30) * 1000, poisson: 0.17, density: 25 },
      supports: [{ joints: [bot[0]], spec: 'PINNED' }, { joints: [bot[nseg]], spec: 'FIXED BUT FX MZ' }],
      loads: [
        { id: 1, type: 'Dead', title: 'SELF WEIGHT', selfweight: -1 },
        { id: 2, type: 'Fluids', title: 'WATER IN TROUGH', member: [
          { members: slab, kind: 'UNI', dir: 'GY', w: -gw * p.depth },
          { members: [wl], kind: 'TRAP', dir: 'GX', w1: -gw * d, w2: 0, d1: 0, d2: d },
          { members: [wr], kind: 'TRAP', dir: 'GX', w1: gw * d, w2: 0, d1: 0, d2: d }] },
        { id: 3, type: 'Live', title: 'LIVE LOAD ON SLAB', member: [{ members: slab, kind: 'UNI', dir: 'GY', w: -(p.walkway || 0) }] }
      ],
      combos: [{ id: 101, title: 'SERVICE DL + WATER', factors: [[1, 1], [2, 1]] }, { id: 201, title: 'ULTIMATE 1.5 DL + 1.5 WATER', factors: [[1, 1.5], [2, 1.5], [3, 1.5]] }]
    };
  }

  // Basic structural check of a .std text (used by tests).
  function lint(text) {
    var lines = text.split(/\r?\n/).filter(function (l) { return l.trim() && l.charAt(0) !== '*'; });
    var errors = [];
    if (!/^STAAD (PLANE|SPACE)/.test(lines[0])) errors.push('first command must be STAAD PLANE/SPACE');
    ['UNIT METER KN', 'JOINT COORDINATES', 'MEMBER INCIDENCES', 'MEMBER PROPERTY', 'SUPPORTS', 'PERFORM ANALYSIS', 'FINISH'].forEach(function (k) {
      if (!lines.some(function (l) { return l.indexOf(k) === 0; })) errors.push('missing ' + k);
    });
    var order = ['JOINT COORDINATES', 'MEMBER INCIDENCES', 'MEMBER PROPERTY', 'SUPPORTS', 'LOAD ', 'PERFORM ANALYSIS', 'FINISH'];
    var last = -1;
    order.forEach(function (k) {
      var i = lines.findIndex(function (l) { return l.indexOf(k) === 0; });
      if (i >= 0 && i < last) errors.push(k + ' out of order');
      if (i >= 0) last = i;
    });
    if (lines[lines.length - 1] !== 'FINISH') errors.push('FINISH must be last');
    // joints referenced by members must exist
    var ji = lines.indexOf('JOINT COORDINATES'), mi = lines.indexOf('MEMBER INCIDENCES');
    var joints = {}, i2;
    for (i2 = ji + 1; i2 < mi; i2++) joints[lines[i2].split(/\s+/)[0]] = true;
    for (i2 = mi + 1; i2 < lines.length && /^\d/.test(lines[i2]); i2++) {
      var t = lines[i2].replace(';', '').split(/\s+/);
      if (!joints[t[1]] || !joints[t[2]]) errors.push('member ' + t[0] + ' uses an undefined joint');
    }
    return errors;
  }

  return { write: write, list: list, boxCulvert: boxCulvert, beam: beam, portal: portal, trough: trough, lint: lint };
});
