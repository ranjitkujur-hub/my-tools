// Copies browser builds of third-party libraries from node_modules into vendor/.
// Run after `npm install`:  npm run vendor
'use strict';
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const nm = path.join(root, 'node_modules');
const vendor = path.join(root, 'vendor');
const fontsDir = path.join(vendor, 'fonts');
fs.mkdirSync(fontsDir, { recursive: true });

// docx (MIT)
fs.copyFileSync(path.join(nm, 'docx/dist/index.iife.js'), path.join(vendor, 'docx.iife.js'));
fs.copyFileSync(path.join(nm, 'docx/LICENSE'), path.join(vendor, 'docx.LICENSE.txt'));

// Noto Sans Devanagari (SIL OFL 1.1), regular + bold, Devanagari + Latin subsets
const fsrc = path.join(nm, '@fontsource/noto-sans-devanagari');
const meta = JSON.parse(fs.readFileSync(path.join(fsrc, 'unicode.json'), 'utf8'));
fs.copyFileSync(path.join(fsrc, 'LICENSE'), path.join(fontsDir, 'OFL.txt'));
let css = '/* Noto Sans Devanagari, SIL Open Font License 1.1 (see OFL.txt).\n' +
  ' * Fonts are embedded as data URIs so they also load when index.html is opened from disk.\n' +
  ' * Generated by scripts/vendor.js. */\n';
for (const subset of ['devanagari', 'latin']) {
  for (const weight of [400, 700]) {
    const file = `noto-sans-devanagari-${subset}-${weight}-normal.woff2`;
    fs.copyFileSync(path.join(fsrc, 'files', file), path.join(fontsDir, file));
    const b64 = fs.readFileSync(path.join(fontsDir, file)).toString('base64');
    css += `@font-face {\n  font-family: 'Noto Sans Devanagari';\n  font-style: normal;\n  font-weight: ${weight};\n  font-display: swap;\n` +
      `  src: url(data:font/woff2;base64,${b64}) format('woff2'), url(./${file}) format('woff2');\n` +
      `  unicode-range: ${meta[subset]};\n}\n`;
  }
}
fs.writeFileSync(path.join(fontsDir, 'fonts.css'), css);
console.log('vendor/ updated');
